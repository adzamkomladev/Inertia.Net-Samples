// Run against a disposable demo-seeded local app with playwright-cli run-code --filename=scripts/check-console-browser.js.
async page => {
  const origin = new URL(page.url()).origin
  if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw new Error('Use a disposable local app.')
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('response', response => { if (response.status() >= 400 && response.status() !== 409) errors.push(`${response.status()} ${response.url()}`) })
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const visit = async (path, heading) => {
    await page.goto(origin + path)
    await page.getByRole('heading', { name: heading, exact: true }).waitFor()
    await page.evaluate(() => document.fonts.ready)
  }
  const shot = async name => { await page.screenshot({ path: `.playwright/shots/${name}.png`, animations: 'disabled' }) }
  const checkWidth = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${page.url()}`)
  const login = async role => {
    await page.context().clearCookies()
    await visit('/login', 'Log in')
    await page.getByRole('textbox', { name: 'E-mail' }).fill(`inertia.demo42.carparker.${role}@yopmail.com`)
    await page.getByRole('textbox', { name: 'Password' }).fill('Password@12345')
    await page.getByRole('button', { name: 'Log in', exact: true }).click()
    await page.waitForURL('**/lots')
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login('admin')
  await visit('/admin/users', 'People')
  await page.getByRole('searchbox', { name: 'Search users' }).fill('Casey')
  await page.waitForURL('**/admin/users?q=Casey')
  await page.getByRole('link', { name: 'Casey Reed', exact: true }).click()
  await page.getByRole('heading', { name: 'Account information' }).waitFor()
  await shot('account-details-desktop')
  await checkWidth()
  await visit('/admin/users', 'People')
  await page.getByRole('searchbox', { name: 'Search users' }).fill('no-such-person-zz')
  await page.getByText('No matching accounts', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await page.getByRole('link', { name: 'Casey Reed', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Create customer', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  await page.keyboard.press('Tab')
  assert(await dialog.evaluate(el => el.contains(document.activeElement)), 'Panel lost focus')
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: 'Create customer', exact: true }).click()
  await dialog.getByLabel('Full name').fill('Browser Customer')
  await dialog.getByLabel('Email address').fill(`browser-${Date.now()}@example.test`)
  await dialog.getByLabel('Initial password').fill('Password@12345')
  await dialog.getByRole('button', { name: 'Create customer', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('link', { name: 'Browser Customer', exact: true }).first().waitFor()
  await shot('people-desktop')
  await visit('/admin/lots', 'Lots & spots')
  await page.getByRole('searchbox', { name: 'Search lots', exact: true }).fill('airport')
  await page.getByRole('status').filter({ hasText: /^1 of/ }).waitFor()
  assert(await page.locator('main a[href*="/admin/lots/"]').count() === 1, 'Lot search failed')
  await page.getByRole('button', { name: 'Clear search' }).click()
  await page.getByRole('button', { name: 'Create lot', exact: true }).click()
  await dialog.waitFor()
  await dialog.getByLabel('Name', { exact: true }).fill('Browser Test Lot')
  await dialog.getByLabel('Area', { exact: true }).fill('Test area')
  await dialog.getByLabel('Address', { exact: true }).fill('12 Browser Street')
  await dialog.getByRole('button', { name: 'Create lot', exact: true }).click()
  await page.waitForURL('**/admin/lots/*')
  await page.getByRole('heading', { name: 'Browser Test Lot', exact: true }).waitFor()
  await visit('/admin/team', 'Team management')
  await page.getByRole('button', { name: 'Add team member', exact: true }).click()
  await dialog.getByLabel('Name', { exact: true }).fill('Browser Guard')
  await dialog.getByLabel('Email', { exact: true }).fill(`guard-${Date.now()}@example.test`)
  await dialog.getByLabel('Initial password').fill('Password@12345')
  await dialog.getByRole('button', { name: 'Create team member', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByText('Browser Guard', { exact: false }).first().waitFor()
  await visit('/admin/sessions', 'Parking sessions')
  await page.locator('tbody button').first().click()
  await dialog.waitFor()
  await shot('session-details-desktop')
  await dialog.getByLabel('Closure note (optional)').fill('Browser verified closure')
  await dialog.getByRole('button', { name: 'Force close session', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Force close', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: /Exit log/ }).click()
  await checkWidth()
  await visit('/admin/bookings', 'All bookings')
  await page.getByRole('searchbox', { name: 'Search bookings' }).fill('zz-no-booking')
  await page.getByText('No matching bookings', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await page.locator('tbody tr').first().waitFor()
  await page.getByRole('button', { name: 'Switch to dark theme' }).first().click()
  await visit('/admin/users', 'People')
  assert(await page.locator('html').getAttribute('class').then(c => c.includes('dark')), 'Theme reset on navigation')
  await shot('people-dark')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('navigation', { name: 'Admin mobile navigation' }).getByRole('link', { name: 'Users', exact: true }).click()
  await page.getByRole('heading', { name: 'People', exact: true }).waitFor()
  await shot('people-mobile-dark')
  assert(await page.locator('main .grid-cols-1').evaluate(el => el.scrollWidth <= el.clientWidth), 'Mobile cards clipped')
  await checkWidth()
  await page.getByRole('button', { name: 'Create customer', exact: true }).click()
  await dialog.waitFor()
  await shot('customer-panel-mobile-dark')
  await checkWidth()
  await page.keyboard.press('Escape')
  await visit('/admin/lots', 'Lots & spots')
  await page.getByRole('button', { name: 'Create lot', exact: true }).click()
  await dialog.waitFor()
  await shot('lot-panel-mobile-dark')
  await dialog.getByRole('switch', { name: 'Open 24 hours' }).click()
  await dialog.getByRole('button', { name: 'Opens', exact: true }).waitFor()
  await checkWidth()
  await page.keyboard.press('Escape')
  await login('guard')
  await visit('/guard', 'Gate console, Airport Long Stay B')
  await shot('guard-mobile')
  await checkWidth()
  await visit('/guard/board', 'Session board')
  await page.getByRole('searchbox', { name: 'Search session board' }).fill('no-plate')
  await checkWidth()
  await visit('/guard/incidents', 'Incidents')
  await page.getByRole('button', { name: 'Report incident', exact: true }).click()
  await dialog.waitFor()
  await shot('incident-panel-mobile')
  await checkWidth()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await visit('/guard', 'Gate console, Airport Long Stay B')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await shot('guard-desktop-dark')
  await checkWidth()
  await page.setViewportSize({ width: 390, height: 844 })
  await login('customer')
  await visit('/lots', 'Find parking')
  await shot('find-parking-mobile')
  await checkWidth()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await shot('find-parking-desktop')
  await checkWidth()
  await visit('/account/bookings', 'Bookings')
  await page.getByRole('searchbox', { name: 'Search your bookings' }).fill('zz-none')
  await page.getByText('No matching bookings', { exact: true }).waitFor()
  await visit('/account/insurance', 'Spot Cover')
  if (await page.getByRole('button', { name: 'File a claim', exact: true }).count()) {
    await page.getByRole('button', { name: 'File a claim', exact: true }).click()
    await dialog.waitFor()
    await shot('claim-panel-desktop')
    await page.keyboard.press('Escape')
  }
  await visit('/lots', 'Find parking')
  await page.getByRole('button', { name: 'Switch to dark theme' }).first().click()
  await shot('find-parking-desktop-dark')
  await page.setViewportSize({ width: 820, height: 1180 })
  await shot('find-parking-tablet-dark')
  await checkWidth()
  assert(errors.length === 0, errors.join('\n'))
  console.log('Console workflows, searches, panels, theme persistence and responsive checks passed.')
}
